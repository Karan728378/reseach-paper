    # TEST 3: Known Treatment Differences Dataset
    # -------------------------------------------------------------------------
    def test_dataset_2_known_treatment_differences(self):
        """Verifies that large prespecified differences produce expected positive RDs and low CMH p-values."""
        rows = []
        run_idx = 1
        # ARIA: 18/20 successes (90%) on T1-T5
        # DATA-CFG: 16/20 successes (80%) on T1-T5
        # BASELINE (ABS+VIS): 12/40 successes (30%) on T1-T5 (6/20 ABS, 6/20 VIS)
        for block in range(1, 5):
            within = 1
            for task in ["T1", "T2", "T3", "T4", "T5"]:
                # ARIA: 4 reps per task -> block 1..4: block 1,2,3 succ, block 4 succ except 2 tasks
                aria_succ = True if (block < 4 or task in {"T1", "T2"}) else False
                rows.append(create_synthetic_row(run_idx, block, within, "ARIA", task, aria_succ))
                run_idx += 1
                within += 1

                datacfg_succ = True if (block < 4) else False
                rows.append(create_synthetic_row(run_idx, block, within, "DATA-CFG", task, datacfg_succ))
                run_idx += 1
                within += 1

                # ABS: 1 succ out of 4 per task (block 1 succ, others fail)
                abs_succ = (block == 1)
                rows.append(create_synthetic_row(run_idx, block, within, "ABS", task, abs_succ))
                run_idx += 1
                within += 1

                # VIS: 1 succ out of 4 per task (block 2 succ, others fail)
                vis_succ = (block == 2)
                rows.append(create_synthetic_row(run_idx, block, within, "VIS", task, vis_succ))
                run_idx += 1
                within += 1

            # T6 runs
            for arm in ["ABS", "VIS", "ARIA", "DATA-CFG"]:
                rows.append(create_synthetic_row(run_idx, block, within, arm, "T6", False))
                run_idx += 1
                within += 1

        csv_path = TEST_DATA_DIR / "dataset_2_known_diff.csv"
        write_csv(csv_path, rows)

        records, val = validate_and_load_summary(csv_path)
        res = analyze_dataset(records, val, alpha=0.05, is_synthetic=True)

        aria_contrast = next(c for c in res["primary_inferential_contrasts"] if c["contrast_id"] == "ARIA_vs_BASELINE")
        
        # Risk difference should be positive and substantial (~ +0.60 to +0.65)
        self.assertGreater(aria_contrast["risk_difference"], 0.50)
        # Newcombe CI lower bound should be strictly positive
        self.assertGreater(aria_contrast["newcombe_95_ci_lower"], 0.25)
        # CMH p-value should be highly statistically significant
        self.assertLess(aria_contrast["cmh_p_unadjusted"], 0.001)
        self.assertTrue(aria_contrast["is_significant_cmh"])

