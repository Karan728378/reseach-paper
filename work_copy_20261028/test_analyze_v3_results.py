def create_synthetic_row(
    run_idx: int,
    block_id: int,
    within_order: int,
    arm: str,
    task_id: str,
    success: bool,
    status: str = "completed",
    error_msg: str = "",
    steps: int = 4,
    time_sec: float = 25.5
) -> dict:
    variant_map = {
        "ABS": "v0-baseline", "VIS": "v0-baseline",
        "ARIA": "v2-aria", "DATA-CFG": "v3-data-attrs"
    }
    targets = {
        "T1": "wh-001", "T2": "mkp-001", "T3": "wh-002",
        "T4": "mse-001", "T5": "wh-001", "T6": "wh-001"
    }
    return {
        "run_index": run_idx,
        "block_id": block_id,
        "within_block_order": within_order,
        "arm": arm,
        "task_id": task_id,
        "variant_mapping": variant_map.get(arm, "v0-baseline"),
        "target_entity": targets.get(task_id, "entity"),
        "success": str(success),
        "score": 1.0 if success else 0.0,
        "total_steps": steps,
        "total_time_seconds": time_sec,
        "status": status,
        "error_message": error_msg,
        "timestamp_end": "2026-10-18T12:00:00"
    }

def write_csv(path: Path, rows: list):
    fieldnames = [
        "run_index", "block_id", "within_block_order", "arm", "task_id",
        "variant_mapping", "target_entity", "success", "score",
        "total_steps", "total_time_seconds", "status", "error_message",
        "timestamp_end"
    ]
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)

