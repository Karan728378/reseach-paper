    # TEST 11: Independent Multicenter CMH Reference Case
    # -------------------------------------------------------------------------
    def test_cmh_multicenter_reference_case(self):
        """Validates CMH calculation against published multicenter clinical trial data (Agresti 2002, p. 231)."""
